import { check, group, sleep } from "k6";
import { Trend } from "k6/metrics";
import { BASE_OPTIONS, buildArrivalRateScenario, numberEnv, requiredEnv } from "../lib/config.js";
import { graphqlRequest, safeJson } from "../lib/graphql.js";

const createTrend = new Trend("calendar_event_create_duration", true);
const updateTrend = new Trend("calendar_event_update_duration", true);
const deleteTrend = new Trend("calendar_event_delete_duration", true);

const SAVE_EVENT_MUTATION = `
mutation SaveEvent($doc: String!) {
  saveDoc(doctype: "Event", doc: $doc) {
    doc {
      name
    }
  }
}
`;

const DELETE_EVENT_MUTATION = `
mutation DeleteEvent($doctype: String!, $name: String!) {
  deleteDoc(doctype: $doctype, name: $name) {
    name
  }
}
`;

function addMinutes(date, minutes) {
  return new Date(date.getTime() + minutes * 60 * 1000);
}

function formatErpDate(date) {
  const year = date.getUTCFullYear();
  const month = String(date.getUTCMonth() + 1).padStart(2, "0");
  const day = String(date.getUTCDate()).padStart(2, "0");
  const hour = String(date.getUTCHours()).padStart(2, "0");
  const minute = String(date.getUTCMinutes()).padStart(2, "0");
  const second = String(date.getUTCSeconds()).padStart(2, "0");
  return `${year}-${month}-${day} ${hour}:${minute}:${second}`;
}

function buildBaseEventDoc() {
  const employeeId = requiredEnv("TEST_EMPLOYEE_ID");
  const employeeEmail = requiredEnv("TEST_EMPLOYEE_EMAIL");
  const roleProfile = requiredEnv("TEST_ROLE_PROFILE");
  const category = __ENV.TEST_EVENT_CATEGORY || "Meeting";
  const color = __ENV.TEST_EVENT_COLOR || "#2563EB";
  const eventType = __ENV.TEST_EVENT_TYPE || "Private";
  const prefix = __ENV.TEST_EVENT_PREFIX || "K6 Load Test";
  const durationMinutes = numberEnv("TEST_EVENT_DURATION_MINUTES", 60);
  const now = new Date();
  const start = addMinutes(now, 5);
  const end = addMinutes(start, durationMinutes);
  const nonce = `${__VU}-${__ITER}-${Date.now()}`;

  return {
    subject: `${prefix} ${nonce}`,
    description: `Generated by k6 write load test ${nonce}`,
    starts_on: formatErpDate(start),
    ends_on: formatErpDate(end),
    custom_role_profile: roleProfile,
    event_category: category,
    color,
    all_day: 0,
    event_type: eventType,
    status: "Open",
    docstatus: 0,
    custom_employee_id: employeeId,
    event_participants: [
      {
        reference_doctype: "Employee",
        reference_docname: employeeId,
        email: employeeEmail,
        custom_role_profile: roleProfile,
      },
    ],
    sync_with_google_calendar: 0,
    google_calendar: "",
    add_video_conferencing: 0,
  };
}

export const options = {
  ...BASE_OPTIONS,
  scenarios: {
    calendar_event_write_load: buildArrivalRateScenario({
      rate: 10,
      duration: "3m",
      preAllocatedVUs: 20,
      maxVUs: 100,
    }),
  },
};

export default function () {
  let eventName = null;

  group("create event", () => {
    const doc = buildBaseEventDoc();
    const response = graphqlRequest(
      SAVE_EVENT_MUTATION,
      { doc: JSON.stringify(doc) },
      { name: "event_create" }
    );
    createTrend.add(response.timings.duration);
    eventName = safeJson(response)?.data?.saveDoc?.doc?.name ?? null;
    check(response, {
      "event created": () => Boolean(eventName),
    });
  });

  group("update event", () => {
    if (!eventName) return;

    const doc = {
      ...buildBaseEventDoc(),
      name: eventName,
      subject: `${__ENV.TEST_EVENT_PREFIX || "K6 Load Test"} UPDATED ${__VU}-${__ITER}`,
    };

    const response = graphqlRequest(
      SAVE_EVENT_MUTATION,
      { doc: JSON.stringify(doc) },
      { name: "event_update" }
    );
    updateTrend.add(response.timings.duration);
    check(response, {
      "event updated": (res) =>
        safeJson(res)?.data?.saveDoc?.doc?.name === eventName,
    });
  });

  group("delete event", () => {
    if (!eventName) return;

    const response = graphqlRequest(
      DELETE_EVENT_MUTATION,
      { doctype: "Event", name: eventName },
      { name: "event_delete" }
    );
    deleteTrend.add(response.timings.duration);
    check(response, {
      "event deleted": (res) =>
        safeJson(res)?.data?.deleteDoc?.name === eventName,
    });
  });

  sleep(numberEnv("SLEEP_SECONDS", 0.2));
}
